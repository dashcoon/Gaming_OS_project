/** Builds an achievement list where the first `unlocked` entries are already earned. */
function achievements(gameId: string, list: [string, string][], unlocked: number): Achievement[] {
  return list.map(([name, description], i) => ({
    id: `${gameId}-ach-${i}`,
    name,
    description,
    unlocked: i < unlocked,
    unlockedAt: i < unlocked ? `2026-0${(i % 9) + 1}-1${i % 9}` : undefined,
  }));
}

